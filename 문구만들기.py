import re
from pathlib import Path


def 받침있나(글자):
    return (ord(글자) - 0xAC00) % 28 != 0


def 이가(낱말):
    return "이" if 받침있나(낱말[-1]) else "가"


def 을를(낱말):
    return "을" if 받침있나(낱말[-1]) else "를"


def 은는(낱말):
    return "은" if 받침있나(낱말[-1]) else "는"


def 말끝고치기(문장):
    """'넣음', '않음' 같은 메모 말투를 '~습니다' 말투로 바꾼다."""
    바꿀것 = {"넣음": "넣었습니다", "않음": "않습니다", "있음": "있습니다", "많음": "많습니다"}
    for 앞, 뒤 in 바꿀것.items():
        if 문장.endswith(앞):
            return 문장[: -len(앞)] + 뒤
    return 문장


def 가게정보읽기(경로):
    정보 = {"홍보": []}
    홍보중 = False
    for 줄 in Path(경로).read_text(encoding="utf-8").splitlines():
        줄 = 줄.strip()
        if not 줄:
            continue
        if 줄.startswith("이번 주 홍보할 것"):
            홍보중 = True
            continue
        if 줄.startswith("-") and 홍보중:
            정보["홍보"].append(줄.lstrip("- ").strip())
            continue
        if ":" in 줄:
            키, 값 = 줄.split(":", 1)
            정보[키.strip()] = 값.strip()
            홍보중 = False
    return 정보


def 홍보내용나누기(정보):
    """홍보 항목에서 신메뉴(이름/가격/설명)와 할인 내용을 뽑아낸다."""
    메뉴 = {"이름": "", "가격": "", "설명": []}
    할인 = ""
    for 항목 in 정보["홍보"]:
        이름 = re.search(r"['‘\"]([^'’\"]+)['’\"]", 항목)
        if 이름 and not 메뉴["이름"]:
            메뉴["이름"] = 이름.group(1)
            가격 = re.search(r"[\d,]+원", 항목)
            if 가격:
                메뉴["가격"] = 가격.group(0)
                뒤 = 항목.split(가격.group(0), 1)[1]
            else:
                뒤 = 항목.split(이름.group(0), 1)[1]
            메뉴["설명"] = [말끝고치기(t.strip()) for t in 뒤.split(",") if t.strip()]
        elif not 할인:
            할인 = 항목
    return 메뉴, 할인


def 해시태그만들기(정보, 메뉴, 할인):
    지역 = [t for t in 정보.get("위치", "").split() if t != "지구"]
    가게 = 정보.get("가게 이름", "")
    특징 = 정보.get("가게 특징", "")
    업종 = ["카페"]
    if "커피" in 가게 or "커피" in 특징:
        업종.append("커피")
    if "스페셜티" in 특징:
        업종.append("스페셜티커피")
    if "로스팅" in 특징:
        업종.append("직접로스팅")
    # 지역 + 업종 + 메뉴를 섞어서, 10개 안에 골고루 들어가게 순서를 정한다
    후보 = [곳 + "카페" for 곳 in 지역[:2]]
    if len(지역) >= 3:
        후보.append(지역[2])
    후보 += [t for t in 업종 if t not in ("카페", "커피")]
    if 지역:
        후보.append(지역[0] + "커피")
    if 메뉴["이름"]:
        후보 += [메뉴["이름"].replace(" ", ""), "신메뉴"]
    글자 = re.findall(r"[가-힣]+", 할인)
    if 할인 and "아메리카노" in 글자:
        후보.append("아메리카노할인")
    후보.append(가게.replace(" ", ""))
    후보 += 업종
    태그 = []
    for t in 후보:
        if t not in 태그:
            태그.append(t)
    return " ".join("#" + t for t in 태그[:10])


